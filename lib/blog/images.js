/**
 * Get image by game name
 * @param {string} gameName - Game identifier (e.g., 'minecraft', 'clashOfClans')
 * @returns {Object} Image object with url, alt, title
 */
export function getGameImage(gameName) {
  return GAME_IMAGES[gameName] || BLOG_IMAGES.defaultArticle;
}

/**
 * Get article hero image
 * @param {string} articleKey - Article identifier
 * @returns {Object} Image object with url, alt, title
 */
export function getArticleImage(articleKey) {
  return ARTICLE_IMAGES[articleKey] || BLOG_IMAGES.defaultArticle;
}

/**
 * Get category image
 * @param {string} category - Category name
 * @returns {Object} Image object with url, alt, title
 */
export function getCategoryImage(category) {
  const key = category.toLowerCase().replace(/[^a-z]/g, '');
  return CATEGORY_IMAGES[key] || CATEGORY_IMAGES.gaming;
}

